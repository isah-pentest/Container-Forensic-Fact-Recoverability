def git_state(repo: Path = REPO_ROOT) -> dict:
    g = ["git", "-c", "safe.directory=*", "-C", str(repo)]
    head = subprocess.run(g + ["rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(g + ["status", "--porcelain", "--untracked-files=no"], capture_output=True,
                           text=True).stdout.strip()
    desc = subprocess.run(g + ["describe", "--tags", "--always"], capture_output=True, text=True).stdout.strip()
    return {"commit": head, "short": head[:12], "describe": desc, "dirty": bool(dirty)}


def _latest(paths) -> Path | None:
    paths = sorted(paths)
    return paths[-1] if paths else None


def _timeline(ev: Evidence, e3_rows: list[dict]) -> dict | None:
    md = [r for r in ev.confirmatory.scored() if r["cell"] == "MD"]
    if not md:
        return None
    lost = {x["run_id"] for x in e3_rows if x["fact"] == "F1" and x["observed_lost"]}
    r = next((x for x in md if x["run_id"] in lost), md[0])
    pkg = Path(r["package"])
    j = journal(pkg)
    ev_rot = read_jsonl(pkg / "sealed" / "rotation_events.jsonl")
    t = ev.params["timing"]
    return {"run_id": r["run_id"], "cell": r["cell"], "t0_ns": j["ACTION_REQUEST"]["wall_ns"],
            "states": {k: v["wall_ns"] for k, v in j.items()}, "epsilon_s": t["epsilon_s"], "grace_s": t["grace_s"],
            "delay_s": t["delay_s"],
            "rotations": [e["wall_ns"] for e in ev_rot if e["event"] == "rotation" and e["source"] == "audit"],
            "deletions": [e["wall_ns"] for e in ev_rot if e["event"] == "deleted" and e["source"] == "audit"]}


def _csv_text(rows: list[dict]) -> str:
    if not rows:
        return ""
    b = io.StringIO()
    keys = list(dict.fromkeys(k for r in rows for k in r))      # union of columns, first-seen order
    w = csv.DictWriter(b, fieldnames=keys, lineterminator="\n", extrasaction="ignore")
    w.writeheader()
    for r in rows:
        w.writerow({k: (json.dumps(v) if isinstance(v, (list, dict)) else v) for k, v in r.items()})
    return b.getvalue()


def claims(res: dict) -> list[dict]:
    """One evidence row per headline number (Section 17.3); the claim text is completed by the authors."""
    p, c = res["primary"], res["analysis_commit"]
    runs = {cell: [r["run_id"] for r in res["runs"] if r["cell"] == cell] for cell in fg.CELLS}
    base = {"analysis_commit": c, "reproduction_status": "regenerated by python -m frx.analysis all"}
    rows = []
    for cell in fg.CELLS:
        v = p["cells"][cell]
        rows.append({**base, "claim_id": f"C-{cell}", "claim_text": f"{cell}: complete record recovered in {v['x']}/{v['n']} runs",
                     "rq_or_hypothesis": "RQ1", "estimand": f"p_{cell}", "metric_ids": "M3;M5",
                     "analysis_function": "frx analyze (frozen)", "table_or_figure": "T4;F3",
                     "run_ids": ";".join(runs[cell]), "artifact_paths": "analysis_outputs/scores.csv",
                     "limitations": "single host, pinned versions, declared operating points (Section 21)"})
    h1 = p["H1"]
    rows.append({**base, "claim_id": "C-H1", "claim_text": (f"Δ_A = {h1['estimate']:+.4f}, randomization p = {h1['p_value']:.4f}; "
                                                         f"95% CI {tuple(round(x, 4) for x in h1['ci_reported'])} ({h1['ci_rule']})"),
                 "rq_or_hypothesis": "H1", "estimand": "Delta_A", "metric_ids": "M6", "analysis_function": "frx analyze (frozen)",
                 "table_or_figure": "T4;F4", "run_ids": "all scored RUN-", "artifact_paths": "analysis_outputs/primary.json",
                 "limitations": "not rejected at alpha = 0.05 is reported as not distinguishable at this precision"})
    fa = res["validity"]["M14_false_attribution"]
    rows.append({**base, "claim_id": "C-FA", "claim_text": f"false attribution {fa['x']}/{fa['n']}",
                 "rq_or_hypothesis": "validity", "estimand": "M14", "metric_ids": "M14",
                 "analysis_function": "frx.analysis.confirmatory.validity", "table_or_figure": "T6",
                 "run_ids": "all scored RUN-", "artifact_paths": "scoring/*/assessment/scores.json", "limitations": ""})
    for key, d in (res.get("e3") or {}).get("by_fact_source", {}).items():
        rows.append({**base, "claim_id": f"C-E3-{key}", "claim_text": (f"{key}: H < 1 rule accuracy {d['H_rule_accuracy']:.3f}; "
                                                                     f"formula Brier {d['M26_brier_formula']:.4f}"),
                     "rq_or_hypothesis": "E3", "estimand": "P(loss | H)", "metric_ids": "M20;M26",
                     "analysis_function": "frx.analysis.mechanism", "table_or_figure": "F7",
                     "run_ids": "D runs + CAL-", "artifact_paths": "e3_headroom.csv", "limitations": "exploratory"})
    return rows


def run_all(evidence: Path, out_root: Path | None = None, draws: int = 100_000, allow_dirty: bool = False) -> dict:
    gs = git_state()
    if gs["dirty"] and not allow_dirty:
        raise RuntimeError("commit the analysis code first: outputs are tied to an analysis commit")
    ev = Evidence(evidence)
    ver = ev.verify()
    if not ver["ok"]:
        raise RuntimeError(f"integrity re-verification failed; no analysis run: {ver['problems'][:10]}")
    out = Path(out_root) if out_root else ev.root / "analysis_outputs" / gs["short"]
    if out.exists() and any(out.iterdir()):
        raise FileExistsError(f"{out} exists; an analysis output set is written once per commit")
    prim = cf.primary(ev, draws)
    runs = cf.run_table(ev)
    res = {"generated_at": datetime.now(timezone.utc).isoformat(), "analysis_commit": gs["commit"],
           "analysis_describe": gs["describe"], "evidence": str(ev.root), "verify": ver,
           "params": ev.params, "contract": ev.contract, "primary": prim, "runs": runs,
           "runs_all": ev.confirmatory.runs, "n_calibration_packages": len(ev.calibration.runs)}
    res["secondary"] = cf.secondary(ev, runs)
    res["validity"] = cf.validity(ev, runs)
    res["sensitivity"] = cf.sensitivity(ev, runs, draws)
    e3_rows = mech.headroom_rows(ev)
    res["e3"] = mech.calibration_summary(e3_rows)
    res["e4"] = mech.loss_stages(ev)
    q = _latest((ev.root / "qualification").glob("g2g3_report_*.json"))
    res["qualification"] = json.loads(q.read_text()) if q else None
    pilot = _latest((ev.root / "qualification" / "pilot").glob("g4_report_*.json"))
    res["pilot"] = json.loads(pilot.read_text()) if pilot else None
    conf = REPO_ROOT / "protocol" / "power" / "confirm.json"
    res["power"] = json.loads(conf.read_text()) if conf.exists() else None
    files = {"results.json": json.dumps({k: v for k, v in res.items() if k not in ("runs_all",)}, indent=2, default=str) + "\n",
             "runs.csv": _csv_text(runs), "e3_headroom.csv": _csv_text(e3_rows),
             "e4_loss_stages.csv": _csv_text(res["e4"]["items"]), "claims_register.csv": _csv_text(claims(res))}
    files.update(tb.render(tb.build(res)))
    tl = _timeline(ev, e3_rows)
    figs = {"F1_architecture.svg": fg.f1_architecture(), "F3_cells.svg": fg.f3_cells(prim),
            "F4_effects.svg": fg.f4_deltas(prim), "F5_fact_source.svg": fg.f5_heatmap(res["secondary"], runs),
            "F6_run_flow.svg": fg.f6_flow(res["validity"], prim), "F7_calibration.svg": fg.f7_calibration(res["e3"], e3_rows)}
    if tl:
        figs["F2_timeline.svg"] = fg.f2_timeline(tl)
    files.update({f"figures/{k}": v for k, v in figs.items()})
    out.mkdir(parents=True, exist_ok=True)
    sums = []
    for rel, text in sorted(files.items()):
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "x") as fh:
            fh.write(text)
        sums.append(f"{hashlib.sha256(text.encode()).hexdigest()}  {rel}\n")
    (out / "SHA256SUMS").write_text("".join(sums))
    return {"out": str(out), "files": len(files), "commit": gs["short"], "verify_ok": ver["ok"],
            "primary_reproduced": prim["_reproduction"]["matches_locked_primary_json"]}


